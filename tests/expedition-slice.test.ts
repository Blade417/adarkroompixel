import { describe, expect, it } from 'vitest';
import { ExpeditionSlice } from '../src/app/expedition-slice';
import { MemoryStorage, scriptedRng } from '../src/core';
import { nodeContent } from '../src/node';
import { EARLY_ENCOUNTERS } from '../src/app/expedition-catalog';
import { WORLD } from '../src/core/data';

describe('isolated first-expedition slice', () => {
  it.each(EARLY_ENCOUNTERS)('selects the original eligible $id encounter, preserving terrain and original stats', entry => {
    const slice = new ExpeditionSlice(nodeContent());
    expect(slice.selectEncounter(entry.id)).toBe(true);
    expect(slice.game.store.get('game.world.map')[WORLD.RADIUS][WORLD.RADIUS - 1]).toBe(';');
    expect(slice.depart()).toBe(true);
    expect(slice.selectEncounter('snarling beast')).toBe(false);
    for (let i = 0; i < 4; i++) expect(slice.move('north')).toBe(true);
    const g = slice.game, event = g.events.active()!;
    expect(g.world.getTerrain()).toBe(entry.terrain);
    expect(event.scene.enemy).toBe(entry.id);
    expect(event.def.isAvailable?.()).toBe(true);
    const original = g.events.content.Encounters.find(e => e.scenes.start.enemy === entry.id)!;
    expect(event.scene).toBe(original.scenes.start);
    expect(event.combat!.enemy.maxHp).toBe(original.scenes.start.health);
    slice.dispose();
  });

  it('uses multiple carried weapons independently, spends bullets and bolas, and stuns the actual enemy', () => {
    const slice = new ExpeditionSlice(nodeContent());
    const g = slice.game;
    slice.selectEncounter('gaunt man');
    slice.pack('bone spear', -1);
    for (const id of ['rifle', 'bullets', 'bolas', 'iron sword']) slice.pack(id, 1);
    slice.depart();
    for (let i = 0; i < 4; i++) slice.move('north');
    g.rng = scriptedRng([.1]);
    const c = g.events.active()!.combat!;
    expect(c.attacks().map(a => a.id)).toEqual(['iron sword', 'rifle', 'bolas']);
    expect(slice.attack('bolas')).toBe(true);
    expect(slice.attack('bolas')).toBe(false);
    g.tick(200);
    expect(c.enemy.stunned).toBe(true);
    expect(g.path.outfit.bolas).toBe(0);
    expect(slice.attack('rifle')).toBe(true);
    expect(g.path.outfit.bullets).toBe(0);
    g.tick(200);
    expect(c.enemy.hp).toBe(1);
    expect(slice.lastStrike?.id).toBe('rifle');
    expect(slice.displayWeapon).toBe('iron sword');
    expect(slice.attack('rifle')).toBe(false);
    g.tick(1700); // the enemy's first scheduled attack is suppressed by the stun
    expect(g.world.health).toBe(10);
    expect(slice.attack('iron sword')).toBe(true);
    expect(slice.wieldedWeapon).toBe('iron sword');
    g.tick(300);
    expect(slice.phase).toBe('loot');
    expect(slice.attack('iron sword')).toBe(false);
    slice.dispose();
  });

  it('falls back to visibly unarmed fists after the last rifle bullet, without inventing ammunition', () => {
    const slice = new ExpeditionSlice(nodeContent());
    const g = slice.game;
    slice.selectEncounter('two-headed creature');
    slice.pack('bone spear', -1);
    slice.pack('rifle', 1);
    slice.pack('bullets', 1);
    slice.depart();
    for (let i = 0; i < 4; i++) slice.move('east');
    const c = g.events.active()!.combat!;
    g.rng = scriptedRng([.1]);
    expect(slice.attack('rifle')).toBe(true);
    g.tick(200);
    expect(c.enemy.hp).toBe(5);
    expect(c.attacks().map(a => a.id)).toEqual(['fists', 'rifle']);
    expect(slice.displayWeapon).toBe('fists');
    expect(slice.attack('rifle')).toBe(false);
    expect(slice.attack('fists')).toBe(true);
    g.tick(100);
    expect(c.enemy.hp).toBe(4);
    expect(slice.displayWeapon).toBe('fists');
    expect(g.path.outfit.bullets).toBe(0);
    slice.dispose();
  });
  it('pays once, fights with original cooldowns, heals, takes weighted loot and returns once', () => {
    const slice = new ExpeditionSlice(nodeContent());
    const g = slice.game;
    expect(g.storage).toBeInstanceOf(MemoryStorage);
    expect(slice.phase).toBe('pack');
    expect(g.path.capacity()).toBe(20);
    expect(slice.depart()).toBe(true);
    expect(slice.depart()).toBe(false);
    expect(g.store.num('stores["cured meat"]')).toBe(4);
    for (let i = 0; i < 4; i++) slice.move('north');
    expect(slice.phase).toBe('combat');
    expect(g.world.water).toBe(16);
    expect(g.path.outfit['cured meat']).toBe(6);
    expect(slice.move('north')).toBe(false);
    const c = g.events.active()!.combat!;
    g.rng = scriptedRng([.1]);
    expect(c.attack('bone spear')).toBe(true);
    expect(c.attack('bone spear')).toBe(false);
    g.tick(2000);
    c.attack('bone spear');
    g.tick(2000);
    expect(c.use('eat')).toBe(true);
    expect(g.path.outfit['cured meat']).toBe(5);
    expect(g.world.health).toBe(10);
    c.attack('bone spear');
    g.tick(300);
    expect(slice.phase).toBe('loot');
    expect(g.events.takeAll('fur')).toBe(1);
    expect(g.events.takeAll('meat')).toBe(1);
    expect(g.events.takeAll('teeth')).toBe(1);
    g.tick(1000);
    g.events.click('leaveBtn');
    // Even rolls that always trigger a fight must respect the three quiet steps after a fight.
    g.rng = scriptedRng([.1]);
    for (let i = 0; i < 4; i++) slice.move('south');
    expect(slice.phase).toBe('home');
    expect(slice.receipt).toMatchObject({ 'cured meat': -4, fur: 1, meat: 1, teeth: 1 });
    expect(g.store.num('stores["bone spear"]')).toBe(1);
    const stores = structuredClone(g.store.get('stores'));
    expect(slice.move('south')).toBe(false);
    expect(slice.depart()).toBe(false);
    expect(g.store.get('stores')).toEqual(stores);
    slice.dispose();
  });

  it('requires food, permits fists, refuses overweight loot, and loses carried supplies on death', () => {
    const slice = new ExpeditionSlice(nodeContent());
    const g = slice.game;
    slice.pack('cured meat', -100);
    expect(slice.depart()).toBe(false);
    slice.pack('cured meat', 8);
    slice.pack('bone spear', -1);
    slice.depart();
    for (let i = 0; i < 4; i++) slice.move('east');
    const combat = g.events.active()!.combat!;
    expect(combat.attacks()[0].id).toBe('fists');
    g.events.active()!.loot = { fur: 99 };
    expect(g.events.takeAll('fur')).toBe(14); // six food take six of twenty slots
    expect(g.path.freeSpace()).toBe(0);
    expect(g.events.take('fur')).toBe(0);
    g.world.setHp(1); combat.player.hp = 1;
    g.rng = scriptedRng([.1]);
    g.tick(1500);
    expect(slice.phase).toBe('dead');
    expect(g.path.outfit).toEqual({});
    expect(g.store.num('stores["cured meat"]')).toBe(4);
    expect(g.store.num('stores.fur')).toBe(0);
    expect(g.cooldowns.isCooling('embarkButton')).toBe(true);
    slice.dispose();
  });
});

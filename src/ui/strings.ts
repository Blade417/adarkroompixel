const TABLES: Record<Language, Record<UiKey, string>> = { zh: ZH, en: EN };

export type Ui = (key: UiKey, ...args: unknown[]) => string;

export function uiStrings(lang: Language): Ui {
  const table = TABLES[lang] ?? EN;
  return (key, ...args) => table[key].replace(/\{(\d+)\}/g, (m, i) => (args[Number(i)] !== undefined ? String(args[Number(i)]) : m));
}

/** every key exists in both languages (checked by the tests) */
export function missingKeys(): string[] {
  return (Object.keys(ZH) as UiKey[]).filter((k) => typeof EN[k] !== 'string' || !EN[k]);
}
